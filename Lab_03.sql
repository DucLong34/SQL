 ---1.Danh Mục vật tư 

 CREATE TABLE dbo_VaTu(
	MaVTu Char(4) CONSTRAINT PK_VaTu PRIMARY KEY , 
	TenVTu VarChar(100) NOT NULL CONSTRAINT UQ_VatTu_Ten UNIQUE ,
	DvTinh VarChar(10) NULL CONSTRAINT DF_VatTu_DvTinh DEFAULT N'cái' ,
	PhanTram Real NULL CONSTRAINT DF_VatTu_PhanTram DEFAULT 0
                       CONSTRAINT CK_VatTu_PhanTram CHECK (PhanTram >= 0 AND PhanTram <= 100)
 );
 GO

 SELECT * FROM dbo_VaTu

 ---2.Danh mục nhà cung cấp

 CREATE TABLE dbo_NHACC(
	MaNhaCc Char(3) NOT NULL CONSTRAINT PK_NHACC PRIMARY KEY ,
	TenNhaCc VarChar(100) NOT NULL CONSTRAINT UQ_NHACC_Ten UNIQUE ,
	DiaChi  VarChar(200) NOT NULL, 
	DienThoai VarChar(20) NULL CONSTRAINT DF_NHACC_DienThoai DEFAULT N'Chưa Có'
 )
 GO

 SELECT * FROM dbo_NHACC

 ---3.Đơn Đặt hàng

 CREATE TABLE dbo_DONDH(
	SoDH Char(4) NOT NULL CONSTRAINT PK_DONDH PRIMARY KEY ,
	NgayDH datetime CONSTRAINT DF_DONDH_NgayDH DEFAULT GETDATE(),
